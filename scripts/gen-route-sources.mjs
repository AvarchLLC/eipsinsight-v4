// Generates src/data/route-sources.generated.ts: a map from each App Router
// URL pattern to its source page.tsx, so the "view source" FAB can link the
// current page to its file on GitHub. Run on prebuild (and manually anytime).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const APP_DIR = path.join(__dirname, '..', 'src', 'app');
const OUT = path.join(__dirname, '..', 'src', 'data', 'route-sources.generated.ts');

/** Walk for every page.tsx under src/app (skipping api routes). */
function findPages(dir, acc = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'api') continue; // no UI pages
      findPages(full, acc);
    } else if (entry.name === 'page.tsx') {
      acc.push(full);
    }
  }
  return acc;
}

/** Convert an app-relative dir to a URL pattern (route groups stripped, dynamics → params). */
function toPattern(relDir) {
  const segs = relDir.split(path.sep).filter(Boolean);
  const urlSegs = [];
  for (const s of segs) {
    if (s.startsWith('(') && s.endsWith(')')) continue; // route group: not in URL
    if (s.startsWith('[[...') && s.endsWith(']]')) urlSegs.push('**'); // optional catch-all
    else if (s.startsWith('[...') && s.endsWith(']')) urlSegs.push('*'); // catch-all
    else if (s.startsWith('[') && s.endsWith(']')) urlSegs.push(':' + s.slice(1, -1));
    else urlSegs.push(s);
  }
  return '/' + urlSegs.join('/');
}

const pages = findPages(APP_DIR);
const rows = pages.map((p) => {
  const relDir = path.relative(APP_DIR, path.dirname(p));
  const pattern = toPattern(relDir) || '/';
  const source = 'src/app/' + path.relative(APP_DIR, p).split(path.sep).join('/');
  const staticSegs = pattern.split('/').filter((s) => s && !s.startsWith(':') && s !== '*' && s !== '**').length;
  return { pattern: pattern === '' ? '/' : pattern, source, staticSegs };
});

// Most-specific first: more static segments, then longer patterns.
rows.sort((a, b) => b.staticSegs - a.staticSegs || b.pattern.length - a.pattern.length);

const body = rows.map((r) => `  { pattern: ${JSON.stringify(r.pattern)}, source: ${JSON.stringify(r.source)} },`).join('\n');
const out = `// AUTO-GENERATED by scripts/gen-route-sources.mjs — do not edit by hand.
// Maps each App Router URL pattern to its source page.tsx (for the GitHub source link).
export interface RouteSource { pattern: string; source: string; }
export const ROUTE_SOURCES: RouteSource[] = [
${body}
];
`;

fs.writeFileSync(OUT, out);
console.log(`[gen-route-sources] wrote ${rows.length} routes to ${path.relative(path.join(__dirname, '..'), OUT)}`);
